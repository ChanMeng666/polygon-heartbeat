// Real-instrument sample playback through external engines:
//  - FluidSynth + GeneralUser GS (SoundFont 2)
//  - sfizz_render + SFZ libraries (Salamander Grand Piano, jRhodes3d, VCSL percussion/glockenspiel)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { TOOLS, LIBS, WORK, SR } from '../config.js';
import { writeMidi } from '../lib/midi.js';
import { readWav } from '../lib/wav.js';

const run = (exe, args) => execFileSync(exe, args, { stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 1 << 26 });

/** Load a rendered WAV and fit it to `len` samples (stereo, SR). */
function fit(file, len) {
  const w = readWav(file);
  if (w.sampleRate !== SR) throw new Error(`${file}: expected ${SR} Hz, got ${w.sampleRate}`);
  const chans = w.channels.length === 1 ? [w.channels[0], w.channels[0]] : w.channels.slice(0, 2);
  return chans.map((c) => { const o = new Float32Array(len); o.set(c.subarray(0, len)); return o; });
}

/** Render one GM track with FluidSynth (built-in reverb/chorus off: effects happen in the mix). */
export function fluid(name, track, bpm, len) {
  const mid = path.join(WORK, `${name}.mid`), wav = path.join(WORK, `${name}.fluid.wav`);
  writeMidi(mid, [{ name, ...track }], bpm);
  run(TOOLS.fluidsynth, ['-ni', '-q', '-g', '0.8', '-r', String(SR), '-O', 'float', '-T', 'wav',
    '-o', 'synth.reverb.active=0', '-o', 'synth.chorus.active=0', '-o', 'synth.polyphony=512',
    '-F', wav, LIBS.generalUser, mid]);
  return fit(wav, len);
}

/** Render one track through an SFZ instrument with sfizz. */
export function sfizz(name, sfzFile, notes, bpm, len, extraCC = []) {
  const mid = path.join(WORK, `${name}.mid`), wav = path.join(WORK, `${name}.sfizz.wav`);
  // A pedal-up at the very end pins End-of-Track, so --use-eot renders the full length
  // (without it sfizz waits for silence, which never comes while the pedal is held).
  const endBeat = (len / SR) * (bpm / 60) - 0.01;
  writeMidi(mid, [{ name, channel: 0, notes, cc: [...extraCC, { t: endBeat, c: 64, v: 0 }] }], bpm);
  run(TOOLS.sfizz, ['--sfz', sfzFile, '--midi', mid, '--wav', wav, '-s', String(SR), '-q', '2', '-p', '256', '--use-eot']);
  return fit(wav, len);
}

// ------------------------------------------------------------- generated SFZ maps for VCSL
const IDIO = 'Idiophones/Struck Idiophones';
const MEMB = 'Membranophones/Struck Membranophones';

function rrGroup(key, files, extra = '') {
  return `<group> key=${key} seq_length=${files.length} ${extra}\n` +
    files.map((f, i) => `<region> sample=${f} seq_position=${i + 1}`).join('\n') + '\n';
}

function velLayers(key, layers) {
  // layers: [[hivel, [files...]], ...] ascending
  let lo = 1, out = '';
  for (const [hi, files] of layers) {
    out += rrGroup(key, files, `lovel=${lo} hivel=${hi}`);
    lo = hi + 1;
  }
  return out;
}

/** Percussion kit built from VCSL one-shots (round-robins + velocity layers). */
export function writeVcslKit() {
  const clap = [1, 2, 3, 4, 5, 6].map((i) => `${IDIO}/Claps/Clap_rr${i}.wav`);
  const sn = (v) => [1, 2].map((r) => `${MEMB}/Snare Drum, Modern 1/Snare2_HitSN_v${v}_rr${r}_Mid.wav`);
  const hh = (v) => [1, 2].map((r) => `${IDIO}/Hi-Hat Cymbal/HiHat_HitC_v${v}_rr${r}_Mid.wav`);
  const sfz = `// Generated by src/instruments/samplers.js — VCSL (CC0) percussion kit
<control> default_path=${LIBS.vcsl.replace(/\\/g, '/')}/
<global> loop_mode=one_shot ampeg_release=0.08
${rrGroup(39, clap, 'amp_veltrack=60')}
${velLayers(38, [[45, sn(3)], [75, sn(5)], [100, sn(6)], [115, sn(7)], [127, sn(9)]])}
${velLayers(42, [[50, hh(1)], [75, hh(2)], [100, hh(3)], [127, hh(4)]])}
${rrGroup(46, [1, 2].map((r) => `${IDIO}/Hi-Hat Cymbal/HiHat_HitO_rr${r}_Mid.wav`))}
${rrGroup(70, ['Down_rr1', 'Up_rr1', 'Down_rr2', 'Up_rr2'].map((s) => `${IDIO}/Shaker, Small/Mid_ShakerHighFaster_${s}.wav`), 'amp_veltrack=80')}
${velLayers(54, [[90, [`${IDIO}/Tambourine 1/Tamb1_Hit_v1_rr1_Mid.wav`]], [127, [`${IDIO}/Tambourine 1/Tamb1_Hit_v2_rr1_Mid.wav`]]])}
${velLayers(50, [[100, [`${IDIO}/Suspended Cymbal 1/susCymb1_hit_f1.wav`]], [127, [`${IDIO}/Suspended Cymbal 1/susCymb1_hit_fff1.wav`]]])}
<group> key=60 <region> sample=${IDIO}/Suspended Cymbal 1/susCymb1_cresc_2s.wav
<group> key=61 <region> sample=${IDIO}/Suspended Cymbal 1/susCymb1_cresc_4s.wav
<group> key=84 <region> sample=${IDIO}/Mark Trees/windchimes_fastAsc1.wav
`;
  const file = path.join(WORK, 'vcsl_kit.sfz');
  fs.writeFileSync(file, sfz);
  return file;
}

/**
 * Glockenspiel from VCSL. Sample names are one octave below the sounding pitch
 * (glock_*_C5 measures ~1054 Hz = C6), so pitch_keycenter = named note + 12.
 */
export function writeVcslGlock() {
  const dir = `${IDIO}/Glockenspiel`;
  const files = fs.readdirSync(path.join(LIBS.vcsl, dir)).filter((f) => f.endsWith('.wav'));
  const NOTE = { C: 0, 'C#': 1, D: 2, 'D#': 3, E: 4, F: 5, 'F#': 6, G: 7, 'G#': 8, A: 9, 'A#': 10, B: 11 };
  const layers = { soft: [1, 60], medium: [61, 95], loud: [96, 127] };
  let regions = '';
  for (const [layer, [lo, hi]] of Object.entries(layers)) {
    const smp = files.map((f) => /^glock_(\w+)_([A-G]#?)(\d)_\d+\.wav$/.exec(f)).filter((m) => m && m[1] === layer)
      .map((m) => ({ file: m[0], key: (Number(m[3]) + 1) * 12 + NOTE[m[2]] + 12 }))
      .sort((a, b) => a.key - b.key);
    smp.forEach((s, i) => {
      const lok = i === 0 ? 0 : Math.floor((smp[i - 1].key + s.key) / 2) + 1;
      const hik = i === smp.length - 1 ? 127 : Math.floor((s.key + smp[i + 1].key) / 2);
      regions += `<region> sample=${dir}/${s.file} pitch_keycenter=${s.key} lokey=${lok} hikey=${hik} lovel=${lo} hivel=${hi}\n`;
    });
  }
  const sfz = `// Generated by src/instruments/samplers.js — VCSL (CC0) glockenspiel
<control> default_path=${LIBS.vcsl.replace(/\\/g, '/')}/
<global> loop_mode=one_shot ampeg_release=0.6 amp_veltrack=70
<group>
${regions}`;
  const file = path.join(WORK, 'vcsl_glock.sfz');
  fs.writeFileSync(file, sfz);
  return file;
}
